/**
 * Build derived mascot assets from the two editable SVG masters.
 *
 *   node scripts/build-assets.js          write outputs
 *   node scripts/build-assets.js --check  exit 1 if any output is stale
 *
 * Masters (edit these only):
 *   src/mascot/mascot-base.svg   Technology robot
 *   src/mascot/mascot-web.svg    Web cat-inspired companion
 *
 * Outputs:
 *   src/mascot/mascot-svgs.js            inline markup module (works on file://)
 *   assets/static/{tech,web}-idle.svg    static fallback / poster
 *   assets/static/{tech,web}-speaking.svg
 *   demo/standalone.html                 single-file demo that opens from file://
 *
 * No dependencies, no network.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const MASTERS = {
  technology: { file: 'src/mascot/mascot-base.svg', prefix: 'tech' },
  web:        { file: 'src/mascot/mascot-web.svg',  prefix: 'web'  },
};

/** Strip the documentation comment and XML noise; keep only the <svg> element. */
export function cleanMaster(raw) {
  const start = raw.indexOf('<svg');
  if (start === -1) throw new Error('master has no <svg> element');
  return raw.slice(start).trim() + '\n';
}

function replaceOnce(src, from, to, label) {
  if (!src.includes(from)) throw new Error(`speaking pose: could not find ${label}`);
  return src.replace(from, to);
}

/** Speaking pose: equalizer bars on, eyes and mouth off (matches concept sheet). */
export function toSpeakingPose(svg, prefix) {
  let out = svg;
  out = replaceOnce(out, `id="${prefix}-speak-bars" opacity="0"`, `id="${prefix}-speak-bars" opacity="1"`, 'speak bars');
  out = replaceOnce(out, `<g id="${prefix}-eye-left"`,  `<g id="${prefix}-eye-left" opacity="0"`,  'left eye');
  out = replaceOnce(out, `<g id="${prefix}-eye-right"`, `<g id="${prefix}-eye-right" opacity="0"`, 'right eye');
  out = out.replace(new RegExp(`(<(?:g|path) id="${prefix}-mouth")`), '$1 opacity="0"');
  return out;
}

function jsString(s) {
  return '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';
}

/**
 * demo/standalone.html: demo/index.html with every ES module inlined.
 * Chromium blocks module imports from file:// (CORS, origin "null"), so the
 * module demo needs `npm run demo`. The standalone file has no imports and
 * opens by double-click. Each module runs in its own function scope.
 */
const STANDALONE_MODULES = {
  '../src/mascot/mascot-controller.js': 'src/mascot/mascot-controller.js',
  '../src/chat/mock-chat-adapter.js':   'src/chat/mock-chat-adapter.js',
  '../src/chat/chat-panel.js':          'src/chat/chat-panel.js',
  '../src/mascot/mascot-roamer.js':     'src/mascot/mascot-roamer.js',
  '../src/mascot/mascot-svgs.js':       null,   // generated below from the masters
};

export function buildStandalone(svgModuleSource) {
  let html = fs.readFileSync(path.join(ROOT, 'demo/index.html'), 'utf8');
  const importRe = /^[ \t]*import \{([^}]+)\}\s+from\s+'([^']+)';[ \t]*\r?\n/gm;
  const blocks = [];
  html = html.replace(importRe, (_, names, spec) => {
    if (!(spec in STANDALONE_MODULES)) throw new Error(`standalone: unknown import ${spec}`);
    const rel = STANDALONE_MODULES[spec];
    const code = rel ? fs.readFileSync(path.join(ROOT, rel), 'utf8') : svgModuleSource;
    if (/^\s*import\s/m.test(code)) throw new Error(`standalone: ${spec} has its own imports`);
    if (/<\/script/i.test(code)) throw new Error(`standalone: ${spec} contains </script`);
    const exported = [...code.matchAll(/^export (?:const|class|function) (\w+)/gm)].map(m => m[1]);
    const body = code.replace(/^export /gm, '');
    const wanted = names.split(',').map(s => s.trim()).filter(Boolean);
    for (const n of wanted) if (!exported.includes(n)) throw new Error(`standalone: ${spec} does not export ${n}`);
    blocks.push(`    // ── inlined from ${rel || 'generated mascot-svgs.js'} ──\n` +
      `    const { ${wanted.join(', ')} } = (() => {\n${body}\n      return { ${wanted.join(', ')} };\n    })();\n`);
    return '';
  });
  if (!blocks.length) throw new Error('standalone: no imports found in demo/index.html');
  const marker = /<script type="module">\r?\n/g;
  if ((html.match(marker) || []).length !== 1) throw new Error('standalone: expected exactly one module script');
  html = html.replace(marker, (m) => m + blocks.join('\n'));
  html = html.replace('<title>LAVAALL Mascot Prototype', '<title>LAVAALL Mascot Prototype (standalone)');
  return '<!-- GENERATED by scripts/build-assets.js from demo/index.html. Opens from file:// (no module imports). -->\n' + html;
}

export function buildOutputs() {
  const outputs = {};
  const inline = {};
  for (const [variant, { file, prefix }] of Object.entries(MASTERS)) {
    const svg = cleanMaster(fs.readFileSync(path.join(ROOT, file), 'utf8'));
    inline[variant] = svg;
    outputs[`assets/static/${prefix}-idle.svg`] = svg;
    outputs[`assets/static/${prefix}-speaking.svg`] = toSpeakingPose(svg, prefix);
  }
  outputs['src/mascot/mascot-svgs.js'] =
    '// GENERATED by scripts/build-assets.js from mascot-base.svg and mascot-web.svg.\n' +
    '// Do not edit by hand; edit the .svg masters and re-run `npm run build:assets`.\n' +
    'export const MASCOT_SVGS = Object.freeze({\n' +
    Object.entries(inline).map(([k, v]) => `  ${k}: ${jsString(v)},`).join('\n') +
    '\n});\n';
  outputs['demo/standalone.html'] = buildStandalone(outputs['src/mascot/mascot-svgs.js']);
  return outputs;
}

function main() {
  const check = process.argv.includes('--check');
  const outputs = buildOutputs();
  const stale = [];
  for (const [rel, content] of Object.entries(outputs)) {
    const abs = path.join(ROOT, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (current === content) continue;
    if (check) { stale.push(rel); continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
    console.log(`wrote ${rel} (${Buffer.byteLength(content)} bytes)`);
  }
  if (check) {
    if (stale.length) { console.error('stale generated assets:\n  ' + stale.join('\n  ')); process.exit(1); }
    console.log('generated assets are up to date');
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
