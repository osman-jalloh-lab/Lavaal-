'use strict';
// Public knowledge pack: generated from existing sources, Technology mounted, Web stub only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const gen = require('../scripts/build-assistant-knowledge');
const knowledge = require('../api/_chat/knowledge');
const { buildMessages } = require('../api/_chat/llm-responder');
const { respond } = require('../api/_chat/responder');

let checks = 0;
function check(name, fn) { fn(); checks++; console.log('ok -', name); }

const committed = JSON.parse(fs.readFileSync(gen.OUT, 'utf8'));
const fresh = gen.build();
const planPresent = fs.existsSync(path.join(gen.PLAN_DIR, 'kb-technology.md'));

check('committed pack matches a fresh generation from the sources (no hand edits)', () => {
  const strip = pack => JSON.stringify({ ...pack, sources: undefined, contentHash: undefined,
    guardrails: planPresent ? pack.guardrails : { ...pack.guardrails, technology: undefined, web: undefined } });
  assert.equal(strip(fresh), strip(committed));
  if (planPresent) assert.equal(fresh.contentHash, committed.contentHash);
});

check('pack is versioned and names its generator', () => {
  assert.equal(committed.version, 1);
  assert.match(committed.note, /GENERATED by scripts\/build-assistant-knowledge\.js/);
  assert.ok(/^[a-f0-9]{64}$/.test(committed.contentHash));
});

check('sources are public files only; internal souls and notes are refused', () => {
  for (const source of committed.sources) assert.doesNotMatch(source.path, /docs\/ops|souls|SOUL_|_SHARED_CONTEXT|MAGNUM|lead/i);
  assert.equal(gen.isForbiddenSource('docs/ops/souls/SOUL_SALES.md'), true);
  assert.equal(gen.isForbiddenSource('/x/docs/ops/souls/_SHARED_CONTEXT.md'), true);
  assert.equal(gen.isForbiddenSource('index.html'), false);
});

const factsText = JSON.stringify(committed.sections);
const allText = factsText + JSON.stringify(committed.missing) + JSON.stringify(committed.behaviour);
check('no prices, stock claims, time promises, stats or internal identities in served facts', () => {
  assert.doesNotMatch(factsText, /[$£€]\s?\d|\b(USD|EUR|GBP)\s*\d|\bLe\s+\d/);
  assert.doesNotMatch(factsText, /\bin stock\b|ready to ship|guaranteed (stock|delivery)/i);
  // Facts themselves still must not promise a time. The missing-information line may use the approved 24-hour team route.
  assert.doesNotMatch(factsText, /within \d+ hours|same[- ]day/i);
  assert.doesNotMatch(allText, /200\+|500\+|since 2018/i);
  assert.doesNotMatch(allText, /jarvis|elevenlabs|wDsJlOXP|soul|founder-rules|ops-rules|password|token/i);
});

check('approved public contacts only', () => {
  assert.equal(committed.contact.email, 'support@lavaall.com');
  assert.equal(committed.contact.whatsapp, '+1 (737) 704-4182');
  assert.equal(committed.contact.reachability, "We're reachable 24/7 on WhatsApp and email");
  const emails = new Set(allText.match(/[a-z0-9.]+@lavaall\.com/gi));
  assert.deepEqual([...emails], ['support@lavaall.com']);
});

check('missing information routes to the team within 24 hours and offers a form', () => {
  const { SERVICE_SLA } = require('../api/_chat/conversation');
  assert.equal(knowledge.missingLine('technology'), SERVICE_SLA + ' Would you like to fill out a quick form?');
  assert.match(knowledge.missingLine('technology'), /within 24 hours/);
  assert.match(knowledge.missingLine('technology'), /form/);
  assert.doesNotMatch(knowledge.missingLine('technology'), /we don't have it|I don't have that information/i);
});

check('behaviour rules from Osman are in the pack', () => {
  const rules = committed.behaviour.join(' ');
  for (const re of [/1-3 short sentences/, /one natural follow-up question/, /family, then model, then color/, /\*\*bold\*\*/, /earlier topic/, /Sierra Leone Krio/, /Haitian Creole/]) assert.match(rules, re);
});

check('Technology is mounted; Web is generated but only a stub', () => {
  assert.equal(knowledge.section('technology').mounted, true);
  assert.equal(knowledge.section('web').mounted, false);
  assert.equal(committed.sections.web.stub, true);
  assert.ok(committed.sections.web.facts.length > 0);
  assert.deepEqual(knowledge.selectFacts('do you build websites and automation', { site: 'web' }), []);
  // Web copy never leaks into the Technology section.
  assert.equal(committed.sections.technology.facts.some(f => /Hermes OS|animated storefront/i.test(f.text)), false);
});

check('every Technology fact names a source file in the repo', () => {
  for (const f of committed.sections.technology.facts) {
    assert.ok(f.source, f.id);
    const file = f.source.split(' ')[0];
    assert.ok(fs.existsSync(path.join(__dirname, '..', file)), f.id + ' -> ' + file);
  }
});

check('catalogue summary matches the live catalogue loader without duplicating products', () => {
  const { loadCatalog } = require('../api/_chat/catalog');
  const total = committed.sections.technology.categories.reduce((n, c) => n + c.products, 0);
  assert.equal(total, loadCatalog().products.length);
  assert.doesNotMatch(JSON.stringify(committed.sections.technology), /iPhone 1\d|Galaxy S2\d/);
});

check('retrieval finds the right public fact and nothing for unknown topics', () => {
  assert.ok(knowledge.selectFacts('Do you deliver to Kenema?').some(f => f.id === 'faq-2'));
  assert.ok(knowledge.selectFacts('Do you work in Guinea?').some(f => f.id === 'coverage-gn'));
  assert.ok(knowledge.selectFacts('Do you work in Liberia?').some(f => f.id === 'coverage-lr'));
  assert.ok(knowledge.selectFacts('Do you sell refurbished laptops?').some(f => f.id === 'faq-3'));
  assert.deepEqual(knowledge.selectFacts('What is your refund policy?'), []);
  assert.deepEqual(knowledge.selectFacts('iphone 16 pro price'), []);
});

check('model prompt carries verified facts and Mark\'s routing and length rules', () => {
  const { SERVICE_SLA } = require('../api/_chat/conversation');
  const ask = 'Do you deliver to Kenema?';
  const [system, user] = buildMessages(ask, respond(ask, {}), {});
  assert.match(user.content, /Verified LAVAALL facts \(public knowledge pack v1\)/);
  assert.match(user.content, /deliver to your doorstep/);
  assert.ok(system.content.includes(SERVICE_SLA), 'unmatched requests route to the 24-hour team line');
  assert.match(system.content, /Never deny carrying or having an item/);
  assert.match(system.content, /follow-up question/);
  assert.match(system.content, /Do not carry an earlier topic/);
  // Mark: no markdown in model replies; bold highlighting is not instructed here.
  assert.doesNotMatch(system.content, /put the key words.*\*\*bold\*\*/i);
  const unknown = 'What is your refund policy?';
  assert.match(buildMessages(unknown, respond(unknown, {}), {})[1].content, /Verified LAVAALL facts: none match this question\./);
});

check('time-promise stripping keeps the rest of the public FAQ', () => {
  assert.equal(gen.noTimePromise('Reach out via WhatsApp or use the quote form below — our team responds within 24 hours.'), 'Reach out via WhatsApp or use the quote form below.');
  assert.equal(gen.noTimePromise('We will follow up with pricing within 24 hours.'), 'We will follow up with pricing.');
});

const { shouldSkipModel } = require('../api/_chat/llm-responder');
check('company questions are answered from the pack before catalogue narrowing, with 0 model calls', () => {
  const cases = [
    ['Do you work in Guinea?', /^Yes, we work in \*\*Guinea\*\*\..*Conakry.*Which city are you in\?$/],
    ['Do you have a branch in Bo?', /^Yes, our \*\*Bo\*\* branch is at 28 Bojon Street\. What can we help you with\?$/],
    ['Where do you operate?', /\*\*Sierra Leone\*\*, \*\*Guinea\*\*, \*\*Liberia\*\* and \*\*Guinea-Bissau\*\*/],
    ['Do you work in Liberia?', /For \*\*Liberia\*\*: We deliver to Liberia, including Monrovia/],
    ['Do you sell wholesale?', /^\*\*Both\*\*\. .*how many\?$/],
    ['Which industries do you serve?', /Healthcare Facilities/],
    ['What does LAVAALL do?', /\*\*enterprise IT equipment\*\*/],
  ];
  for (const [ask, re] of cases) {
    const r = respond(ask, {});
    assert.equal(shouldSkipModel(r), 'knowledge-answer', ask);
    assert.match(r.text, re, ask);
    assert.equal((r.text.match(/\?/g) || []).length, 1, 'one follow-up question: ' + ask);
    assert.ok((r.text.match(/[.!?](\s|$)/g) || []).length <= 4, 'short: ' + ask);
    assert.doesNotMatch(r.text, /We don't carry|in our catalogue/, ask);
  }
});

check('questions the pack cannot answer get the plain missing-information line', () => {
  for (const ask of ['Who owns LAVAALL?', 'What is your warranty?', 'What is your return policy?']) {
    const r = respond(ask, {});
    assert.equal(shouldSkipModel(r), 'knowledge-answer', ask);
    assert.equal(r.text, knowledge.missingLine('technology'));
  }
});

check('existing product, delivery, service and handoff paths are untouched', () => {
  assert.equal(shouldSkipModel(respond('iPhone 16', {})), 'product-guide');
  assert.equal(shouldSkipModel(respond('Do you deliver to Kenema?', {})), 'faq-delivery');
  assert.equal(shouldSkipModel(respond('How do you handle wholesale requests?', {})), 'service-help');
  assert.equal(shouldSkipModel(respond('I want to speak to someone', {})), 'handoff-intake');
  // Mid-flow slot fills are never hijacked.
  assert.notEqual(shouldSkipModel(respond('Do you have a branch in Bo?', { awaiting: 'handoff-name', handoffDraft: { name: '', contact: '', topic: '' } })), 'knowledge-answer');
  // Other languages keep the existing paths (the pack is English).
  assert.notEqual(shouldSkipModel(respond('Travaillez-vous en Guinée ?', {})), 'knowledge-answer');
});

console.log('knowledge pack checks:', checks);
