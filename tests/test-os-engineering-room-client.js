'use strict';
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const win = { atob: s => Buffer.from(s, 'base64').toString('binary'), location: { search: '' } };
const sandbox = { window: win, TextDecoder, Uint8Array, URLSearchParams, setTimeout: () => 0,
  document: { querySelector: () => null, querySelectorAll: () => [], documentElement: { setAttribute() {}, getAttribute: () => 'dark' } }, location: { hash: '' }, navigator: {}, Intl };
vm.createContext(sandbox);
for (const f of ['core.js', 'harness.js']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../api/os/_client', f), 'utf8'), sandbox);
const OS = win.OS;
const payload = { project: { name: '<Example>' } };
win.location.search = '?intake=' + Buffer.from(JSON.stringify(payload)).toString('base64url');
const data = { harness: { groups: [{ id: 'intake', label: 'New from intake', projects: [{ name: 'stub-example', label: 'Example' }] }], status: [] }, intakes: [{ id: 'intake-1', projectId: 'stub-example', goalId: 'goal-123', status: 'submitted' }] };
const html = OS.views.harness.render({ data });
assert(html.includes('<section class="harness-execution" id="harness-intake">'));
assert(html.includes('Example — Pending — from intake'));
assert(html.includes('data-intake-project="stub-example"'));
let added = '', scrolled = false;
OS.intakeReview.focusCard({ classList: { add: c => { added = c; }, remove() {} }, scrollIntoView: () => { scrolled = true; } });
assert.equal(added, 'harness-intake-focus'); assert(scrolled);
const confirmation = OS.intakeReview.approvalHtml(payload, { approval_id: 'appr-1', expires_at: '2026-11-23T00:00:00Z' });
assert(confirmation.includes('&lt;Example&gt;') && !confirmation.includes('<Example>'));
assert(confirmation.includes('after submission') && confirmation.includes('Goals &amp; handoffs'));
const query = OS.harnessSelection.query('?project=stub-example&goal=goal-123');
assert.equal(query.project, 'stub-example'); assert.equal(query.goal, 'goal-123');
assert.equal(OS.harnessSelection.findProject(data.harness.groups, query.project).group, 'intake');
assert.equal(OS.harnessSelection.findProject(data.harness.groups, 'missing'), null);
assert.equal(OS.harnessSelection.query('?project=%3Cbad%3E&goal=bad').project, '');
console.log('test-os-engineering-room-client: PASS');
